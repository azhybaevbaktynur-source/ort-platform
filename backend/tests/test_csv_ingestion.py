import io
import pytest
from app.services.csv_service import CsvService
from app.db.firebase import mock_firestore_db


SAMPLE_VALID_CSV = '''section,topic,difficulty,stem,option_a,option_b,option_c,option_d,correct_option,explanation
math_1,algebra,medium,"Эгер $y = 2x + 4$ болсо жана $x=3$ болсо, $y$ тапкыла:",8,10,12,6,B,"Түшүндүрмө: $2(3)+4 = 10$"
analogies,word_pairs,easy,"Күн : Жарык","Ай : Түн","Суу : Өмүр","От : Жылуулук","Жамгыр : Шамал",C,"От жылуулук берет"
grammar,syntax,hard,"Төмөнкү сүйлөмдө кайсы сөз өтмө мааниде?","Аскар келди","Алтын колдуу уста","Китеп окуду","Суу акты",B,"Алтын колдуу - өтмө маани"
'''

SAMPLE_INVALID_CSV = """section,topic,difficulty,stem,option_a,option_b,option_c,option_d,correct_option,explanation
invalid_sec,algebra,medium,Суроо,1,2,3,4,Z,
math_1,algebra,medium,,1,2,3,4,A,
"""


class TestCsvIngestion:
    def test_validate_valid_csv(self):
        csv_bytes = SAMPLE_VALID_CSV.strip().encode("utf-8")
        report = CsvService.validate_csv(csv_bytes, language="ky")

        assert report.totalRows == 3
        assert report.validRowsCount == 3
        assert report.invalidRowsCount == 0
        assert len(report.errors) == 0
        assert len(report.previewQuestions) == 3

        # Verify Kyrgyz characters properly preserved
        q1 = report.previewQuestions[0]
        assert "тапкыла" in q1.stem
        assert q1.correct_option == "B"

        q2 = report.previewQuestions[1]
        assert "Өмүр" in q2.option_b  # Contains Kyrgyz letter Ө
        assert q2.correct_option == "C"

        q3 = report.previewQuestions[2]
        assert "өтмө" in q3.stem  # Contains Kyrgyz letter ө
        assert q3.correct_option == "B"

    def test_validate_invalid_csv(self):
        csv_bytes = SAMPLE_INVALID_CSV.strip().encode("utf-8")
        report = CsvService.validate_csv(csv_bytes, language="ky")

        assert report.totalRows == 2
        assert report.validRowsCount == 0
        assert report.invalidRowsCount == 2
        assert len(report.errors) > 0

        # Row 2 (first data row): invalid section and invalid correct_option 'Z'
        error_fields = {e.field for e in report.errors}
        assert "section" in error_fields or "correct_option" in error_fields

    def test_batch_ingest_csv_to_firestore(self):
        csv_bytes = SAMPLE_VALID_CSV.strip().encode("utf-8")
        result = CsvService.ingest_csv(csv_bytes, created_by_user_id="inst_test", batch_size=2, language="ky")

        assert result.success is True
        assert result.importedCount == 3
        assert result.failedCount == 0
        assert result.batchCount == 2  # 3 items with batch_size 2 => 2 batches
        assert len(result.importedIds) == 3

        # Verify docs in mock database
        stored_questions = mock_firestore_db.collection("questions").get()
        assert len(stored_questions) == 3
        first_doc = stored_questions[0].to_dict()
        assert first_doc["createdBy"] == "inst_test"
        assert "stem" in first_doc

    def test_ingest_csv_as_fixed_mock_test_creates_exam_set(self):
        csv_bytes = SAMPLE_VALID_CSV.strip().encode("utf-8")
        result = CsvService.ingest_csv(
            csv_bytes,
            created_by_user_id="inst_test",
            batch_size=10,
            exam_type="full_main",
            mock_test_title="ОРТ Негизги Тест 2026 №3",
            language="ky",
        )

        assert result.success is True
        assert result.importedCount == 3
        target_set_id = result.examSetId or result.createdTemplateId
        assert target_set_id is not None
        assert target_set_id.startswith("exam_") or target_set_id.startswith("test_")

        # Verify ExamSet created in Firestore
        exam_doc = mock_firestore_db.collection("mock_test_templates").document(target_set_id).get()
        assert exam_doc.exists
        exam_data = exam_doc.to_dict()
        assert exam_data["title"] == "ОРТ Негизги Тест 2026 №3"
        assert exam_data["language"] == "ky"
        assert len(exam_data["questionIds"]) == 3

    def test_section_alias_normalization(self):
        alias_csv = '''section,topic,difficulty,stem,option_a,option_b,option_c,option_d,correct_option
reading_comprehension,reading,easy,Текст суроосу,A,B,C,D,A
math1,algebra,medium,Математика 1,1,2,3,4,B
чтение_и_понимание,reading,medium,Суроо,A,B,C,D,C
аналогиялар,pairs,easy,Аналогия,1,2,3,4,D
'''
        report = CsvService.validate_csv(alias_csv.strip().encode("utf-8"), language="ky")
        assert report.validRowsCount == 4
        assert report.invalidRowsCount == 0
        assert report.previewQuestions[0].section.value == "reading"
        assert report.previewQuestions[1].section.value == "math_1"
        assert report.previewQuestions[2].section.value == "reading"
        assert report.previewQuestions[3].section.value == "analogies"

    def test_csv_id_column_ignored_and_autogenerated(self):
        csv_with_ids = '''id,section,topic,difficulty,stem,option_a,option_b,option_c,option_d,correct_option
CUSTOM_INSTRUCTOR_ID_999,math_1,algebra,medium,Суроо,1,2,3,4,A
'''
        result = CsvService.ingest_csv(csv_with_ids.strip().encode("utf-8"), created_by_user_id="inst_1", language="ky")
        assert result.success is True
        assert len(result.importedIds) == 1
        generated_id = result.importedIds[0]
        assert generated_id != "CUSTOM_INSTRUCTOR_ID_999"
        assert generated_id.startswith("q_")
        # Ensure it was stored with the generated id, not custom id
        assert mock_firestore_db.collection("questions").document(generated_id).get().exists
        assert not mock_firestore_db.collection("questions").document("CUSTOM_INSTRUCTOR_ID_999").get().exists

    def test_global_exam_id_and_language_injection(self):
        csv_content = '''section,stem,option_a,option_b,option_c,option_d,correct_option,language
math_1,Тестовый вопрос,1,2,3,4,A,ky
'''
        # Pass global exam_id and language="ru"; in-file language "ky" must be overridden
        report = CsvService.validate_csv(
            csv_content.strip().encode("utf-8"),
            language="ru",
            exam_id="exam_target_777",
        )
        assert report.validRowsCount == 1
        q = report.previewQuestions[0]
        assert q.language == "ru"
        assert q.exam_set_id == "exam_target_777"
        assert q.topic == "General"  # Defaults gracefully without error

    def test_legacy_bilingual_and_optional_columns_safe_parsing(self):
        legacy_csv = '''section,stem_ky,stem_ru,option_a_ky,option_a_ru,option_b_ky,option_b_ru,option_c_ky,option_c_ru,option_d_ky,option_d_ru,correct_option
math_1,Кыргызча суроо,Русский вопрос,10,10,20,20,30,30,40,40,B
'''
        # Validate for Russian
        report_ru = CsvService.validate_csv(legacy_csv.strip().encode("utf-8"), language="ru")
        assert report_ru.validRowsCount == 1
        assert report_ru.previewQuestions[0].stem == "Русский вопрос"

        # Validate for Kyrgyz
        report_ky = CsvService.validate_csv(legacy_csv.strip().encode("utf-8"), language="ky")
        assert report_ky.validRowsCount == 1
        assert report_ky.previewQuestions[0].stem == "Кыргызча суроо"

    def test_cyrillic_correct_option_normalization(self):
        cyrillic_csv = '''section,stem,option_a,option_b,option_c,option_d,correct_option
math_1,Суроо 1,A,B,C,D,А
math_2,Суроо 2,A,B,C,D,В
analogies,Суроо 3,A,B,C,D,С
grammar,Суроо 4,A,B,C,D,Д
'''
        report = CsvService.validate_csv(cyrillic_csv.strip().encode("utf-8"), language="ky")
        assert report.validRowsCount == 4
        opts = [q.correct_option for q in report.previewQuestions]
        assert opts == ["A", "B", "C", "D"]

    def test_bulletproof_error_handling_never_crashes(self):
        broken_csv = '''section,stem,option_a,option_b
math_1,Суроо без вариантов C и D,1,2
invalid_sec,Суроо,1,2
'''
        report = CsvService.validate_csv(broken_csv.strip().encode("utf-8"), language="ky")
        assert report.totalRows == 2
        assert report.validRowsCount == 0
        assert report.invalidRowsCount == 2
        assert len(report.errors) >= 2
        # Check that errors detail the missing fields cleanly
        err_fields = [e.field for e in report.errors]
        assert "option_c" in err_fields or "correct_option" in err_fields

